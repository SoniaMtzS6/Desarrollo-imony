    $admin = $result->fetch_assoc();
    $stmt->close();
    */

    // Código local
    $stmt = $conn->prepare("SELECT * FROM administradores WHERE id = ?");
    $stmt->bind_param("i", $idAdmin);
    $stmt->execute();
    $result = $stmt->get_result();
    $admin = $result->fetch_assoc();
    $stmt->close();
}


