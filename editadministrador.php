    $selected = ($admin && $admin['id_empresa'] == $row['ID_EMPRESA']) ? 'selected' : '';
    $empresa .= '<option value="' . $row['ID_EMPRESA'] . '" ' . $selected . '>' . $row['NOMBRE_EMPRESA'] . '</option>';
}


$conn->close();
